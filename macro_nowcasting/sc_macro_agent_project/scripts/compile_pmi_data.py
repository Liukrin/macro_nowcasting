all_rows = []

for date_str in sorted(all_dates):
    row = {'日期': datetime.strptime(date_str + '-01', '%Y-%m-%d')}

    # PMI headline
    row['PMI'] = pmi_headline.get(date_str, None)

    # Core sub-indices
    core = core_sub.get(date_str, {})
    for col in ['生产', '新订单', '原材料库存', '从业人员', '供应商配送时间']:
        row[col] = core.get(col, None)

    # Extended sub-indices
    ext = ext_sub.get(date_str, {})
    for col in ['新出口订单', '进口', '采购量', '主要原材料购进价格', '出厂价格', '产成品库存', '在手订单', '生产经营活动预期']:
        row[col] = ext.get(col, None)

    all_rows.append(row)

